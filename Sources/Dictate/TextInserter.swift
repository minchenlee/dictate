import AppKit
import Carbon.HIToolbox
import DictateCore

/// Inserts text at the focused field: put it on the pasteboard, post ⌘V, then
/// restore the previous pasteboard contents. Posting keys needs Accessibility.
enum TextInserter {
    /// Returns the plan used, so the caller can tell the user when it fell back.
    @discardableResult
    static func insert(_ text: String) -> InsertPlan {
        let plan = InsertPlan.decide(accessibilityTrusted: AXIsProcessTrusted())
        guard plan == .pasteAndRestore else {
            let pb = NSPasteboard.general
            pb.clearContents()
            pb.setString(text, forType: .string)
            return plan
        }
        let pb = NSPasteboard.general
        let saved = snapshot(pb)

        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // Tell clipboard managers not to record this transient write.
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pb.writeObjects([item])
        let ourChange = pb.changeCount

        postPaste()

        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) {
            // Only restore if nobody else wrote to the pasteboard meanwhile.
            guard pb.changeCount == ourChange else { return }
            pb.clearContents()
            if !saved.isEmpty { pb.writeObjects(saved) }
        }
        return plan
    }

    private static func snapshot(_ pb: NSPasteboard) -> [NSPasteboardItem] {
        (pb.pasteboardItems ?? []).map { old in
            let copy = NSPasteboardItem()
            for type in old.types {
                if let data = old.data(forType: type) { copy.setData(data, forType: type) }
            }
            return copy
        }
    }

    private static func postPaste() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let v = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}
